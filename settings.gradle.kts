rootProject.name = "gboard-patches"

// The Morphe patches plugin is published to GitHub Packages.
// Provide credentials in ~/.gradle/gradle.properties (gpr.user / gpr.key) or
// via GITHUB_ACTOR / GITHUB_TOKEN when building online.
pluginManagement {
    repositories {
        gradlePluginPortal()
        google()
        maven {
            name = "GitHubPackages"
            url = uri("https://maven.pkg.github.com/MorpheApp/registry")
            credentials {
                username = providers.gradleProperty("gpr.user").orNull ?: System.getenv("GITHUB_ACTOR")
                password = providers.gradleProperty("gpr.key").orNull ?: System.getenv("GITHUB_TOKEN")
            }
        }
        maven { url = uri("https://jitpack.io") }
    }
}

plugins {
    id("app.morphe.patches") version "1.3.3"
